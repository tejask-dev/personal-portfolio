import { resume as r } from "./content.mjs";

const html = (s) => s.replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const tex = (s) => s.replace(/[\\{}%$&#_^~]/g, c => ({ "\\": "\\textbackslash{}", "{": "\\{", "}": "\\}", "%": "\\%", "$": "\\$", "&": "\\&", "#": "\\#", "_": "\\_", "^": "\\textasciicircum{}", "~": "\\textasciitilde{}" }[c]));
const anchor = (href, label) => `<a href="${html(href)}"${href.startsWith("https:") ? ' target="_blank" rel="noreferrer"' : ""}>${html(label)}</a>`;
const texLink = (href, label) => `\\href{${tex(href)}}{${tex(label)}}`;

export function renderHtml(css) {
  const entry = e => `<article><div class="entry-heading"><h3>${e.href ? anchor(e.href, e.title) : html(e.title)}</h3><p class="dates">${html(e.dates)}</p></div><p class="organization">${html(e.detail)}</p>${e.bullets ? `<ul>${e.bullets.map(b => `<li>${html(b)}</li>`).join("")}</ul>` : ""}</article>`;
  return `<!doctype html>
<!-- Generated by scripts/build-resume.mjs from resume/content.mjs. -->
<html lang="en"><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${html(r.name)} | Resume</title><meta name="description" content="${html(r.description)}" /><meta name="theme-color" content="#ffffff" /><link rel="canonical" href="https://tejasskaushik.com/resume" />
<style>${css}</style></head><body>
<a class="skip-link" href="#resume">Skip to resume</a><nav class="toolbar" aria-label="Resume actions"><a href="/#about">← About Tejass</a><a class="download" href="/Tejass-Kaushik-Resume.pdf" download>Download PDF</a></nav>
<main id="resume" tabindex="-1"><header><h1>${html(r.name)}</h1><p class="location">${html(r.location)}</p><ul class="contact" aria-label="Email and website">${r.contacts.slice(0, 2).map(c => `<li>${anchor(c.href, c.label)}</li>`).join("")}</ul><ul class="contact" aria-label="GitHub and LinkedIn">${r.contacts.slice(2).map(c => `<li>${anchor(c.href, c.label)}</li>`).join("")}</ul></header>
<section aria-labelledby="education-heading"><h2 id="education-heading">Education</h2>${entry(r.education)}</section>
<section aria-labelledby="experience-heading"><h2 id="experience-heading">Experience</h2>${r.experience.map(entry).join("")}</section>
<section aria-labelledby="research-heading"><h2 id="research-heading">Research</h2>${entry(r.research)}</section>
<section aria-labelledby="projects-heading"><h2 id="projects-heading">Projects</h2>${r.projects.map(p => `<article class="project"><h3>${anchor(p.href, p.title)}${p.stack ? ` <span class="project-stack">| ${html(p.stack)}</span>` : ""}</h3><p>${html(p.body)}</p></article>`).join("")}</section>
<section aria-labelledby="skills-heading"><h2 id="skills-heading">Technical skills</h2><dl class="skills">${r.skills.map(s => `<div><dt>${html(s.label)}</dt><dd>${html(s.value)}</dd></div>`).join("")}</dl></section>
</main></body></html>\n`;
}

export function renderTex(template) {
  const entry = e => `\\resumeSubheading{${e.href ? texLink(e.href, e.title) : tex(e.title)}}{${tex(e.dates)}}{${tex(e.detail)}}{}
${e.bullets ? `\\resumeItemListStart\n${e.bullets.map(b => `\\resumeItem{${tex(b)}}`).join("\n")}\n\\resumeItemListEnd` : ""}`;
  const section = (name, entries) => `\\section{${name}}\n\\resumeSubHeadingListStart\n${entries.map(entry).join("\n")}\n\\resumeSubHeadingListEnd`;
  const body = `\\begin{center}
\\textbf{\\Huge \\scshape ${tex(r.name)}} \\\\ \\vspace{2pt}
\\small ${tex(r.location)} \\\\ \\vspace{2pt}
${r.contacts.slice(0, 2).map(c => texLink(c.href, c.label)).join(" $|$ ")} \\\\ \\vspace{2pt}
${r.contacts.slice(2).map(c => texLink(c.href, c.label)).join(" $|$ ")}
\\end{center}
${section("Education", [r.education])}
${section("Experience", r.experience)}
${section("Research", [r.research])}
\\section{Projects}
\\resumeSubHeadingListStart
${r.projects.map(p => `\\item\\small{\\textbf{${texLink(p.href, p.title)}}${p.stack ? ` $|$ ${tex(p.stack)}` : ""} \\\\ ${tex(p.body)}}\\vspace{-4pt}`).join("\n")}
\\resumeSubHeadingListEnd
\\section{Technical Skills}
\\begin{itemize}[leftmargin=0.15in, label={}]
\\small{\\item{${r.skills.map(s => `\\textbf{${tex(s.label)}}: ${tex(s.value)}`).join(" \\\\\n")}}}
\\end{itemize}`;
  return template.replace("%%RESUME_BODY%%", body);
}

export const resumeText = [r.name, r.location, ...r.contacts.map(c => c.label), r.education.title, r.education.dates, r.education.detail, ...[...r.experience, r.research].flatMap(e => [e.title, e.dates, e.detail, ...e.bullets]), ...r.projects.flatMap(p => [p.title, p.stack, p.body]), ...r.skills.flatMap(s => [s.label, s.value])];
